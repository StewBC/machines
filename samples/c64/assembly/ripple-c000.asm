* = $C000

BITMAP  = $2000
SCREEN  = $0400

ptr     = $fb
ptr2    = $fd

start:
    sei

    lda $dd00
    and #$fc
    ora #$03            ; VIC bank 0: $0000-$3fff
    sta $dd00

    lda #$00
    sta $d020
    sta $d021

    lda #$3b            ; bitmap mode, display on, 25 rows
    sta $d011

    lda #$08            ; 40 columns, hires bitmap
    sta $d016

    lda #$18            ; screen=$0400, bitmap=$2000
    sta $d018

    jsr clear_screen_colors

main_loop:
    jsr clear_bitmap
    jsr draw_frame
    jsr delay

    clc
    lda frame_phase
    adc #53             ; about 1.3 radians in 256-step phase
    sta frame_phase

    jmp main_loop


clear_bitmap:
    lda #<BITMAP
    sta ptr
    lda #>BITMAP
    sta ptr + 1

    ldx #32             ; 32 pages = 8192 bytes
    ldy #0
    lda #0

clear_bitmap_page:
    sta (ptr),y
    iny
    bne clear_bitmap_page

    inc ptr + 1
    dex
    bne clear_bitmap_page
    rts


clear_screen_colors:
    ; In hires bitmap mode, screen nybbles select bit-1 and bit-0 colors.
    ; $10 gives white pixels on black cells.
    lda #$10
    ldx #0

clear_screen_loop:
    sta SCREEN,x
    sta SCREEN + $0100,x
    sta SCREEN + $0200,x
    sta SCREEN + $02e8,x      ; enough to cover 1000 bytes total
    inx
    bne clear_screen_loop
    rts


draw_frame:
    lda #<phase_table
    sta ptr2
    lda #>phase_table
    sta ptr2 + 1

    lda #0
    sta z_index

z_loop:
    ldx z_index
    lda ybase_table,x
    sta base_y

    lda xbase_table,x
    sta base_x

    lda #0
    sta x_index

x_loop:
    ; py = ybase[z] + cosoff[phase_table[z][x] + frame_phase]
    ldy #0
    lda (ptr2),y
    clc
    adc frame_phase
    tay

    lda cosoff_table,y
    clc
    adc base_y
    sta py

    ; px = xbase[z] + 4*x
    lda x_index
    asl
    asl
    clc
    adc base_x
    sta px

    jsr plot

    ; advance phase table pointer
    inc ptr2
    bne phase_ptr_ok
    inc ptr2 + 1

phase_ptr_ok:
    inc x_index
    lda x_index
    cmp #51
    bne x_loop

    inc z_index
    lda z_index
    cmp #51
    bne z_loop

    rts


plot:
    ; px must be 0..255 here. This demo stays inside that.
    lda py
    cmp #200
    bcs plot_done

    tay
    lda ylo_table,y
    sta ptr
    lda yhi_table,y
    sta ptr + 1

    lda px
    and #$f8            ; C64 bitmap horizontal byte offset: column * 8
    clc
    adc ptr
    sta ptr
    bcc plot_no_carry
    inc ptr + 1

plot_no_carry:
    lda px
    and #7
    tay
    lda mask_table,y

    ldy #0
    ora (ptr),y
    sta (ptr),y

plot_done:
    rts


