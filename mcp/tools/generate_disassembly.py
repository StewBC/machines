"""Generate opcode metadata from the authoritative shared C decoder.

Run from any directory; --check detects opcode AND formatting source drift.
"""
from pathlib import Path
import argparse
import hashlib
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'src/shell/tools/disasm_6502/disasm_6502.c'
OUTPUT = ROOT / 'mcp/src/machines_mcp/codecs/_disassembly_opcodes.py'


def generated():
    source = SOURCE.read_text()
    table = source.split('static const opcode_info opcode_table[256] = {', 1)[1].split('};', 1)[0]
    entries = []
    pattern = r'OP\("([A-Z]+)",\s*DISASM_MODE_([A-Z]+),\s*(\d)\)|\bXX\b'
    for match in re.finditer(pattern, table):
        entries.append((match[1], match[2], int(match[3])) if match[1] else (None, 'IMP', 1))
    if len(entries) != 256:
        raise ValueError('Expected exactly 256 NMOS opcode entries')
    overrides = {}
    for match in re.finditer(r'case (0x[0-9A-Fa-f]+): return OP65\("([A-Z]+)",\s*DISASM_MODE_([A-Z]+),\s*(\d)\);', source):
        overrides[int(match[1], 16)] = (match[2], match[3], int(match[4]))
    if len(overrides) != 27:
        raise ValueError('65C02 source shape changed: inspect generator')
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    return ('# Generated by mcp/tools/generate_disassembly.py; do not edit.\n'
            f'SOURCE_SHA256 = {digest!r}\n'
            'NMOS = (\n' + ''.join(f'    {entry!r},\n' for entry in entries) + ')\n'
            f'CMOS_OVERRIDES = {overrides!r}\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generated()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Shared disassembler changed; regenerate and verify formatting parity')
    else:
        OUTPUT.write_text(content)
